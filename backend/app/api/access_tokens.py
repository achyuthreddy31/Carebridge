import datetime
from fastapi import APIRouter, Depends, HTTPException, status
from sqlalchemy.orm import Session
from app.database import get_db
from app.models.user import User
from app.models.patient import Patient
from app.models.access_token import AccessToken
from app.schemas.access import CreateAccessTokenRequest, AccessTokenResponse
from app.auth.rbac import get_current_patient
from app.services.otp_service import OTPService

router = APIRouter(prefix="/access-tokens", tags=["Temporary Access Tokens"])

@router.post("", response_model=AccessTokenResponse)
def create_access_token(
    payload: CreateAccessTokenRequest = None,
    patient_data: tuple[User, Patient] = Depends(get_current_patient),
    db: Session = Depends(get_db)
):
    """
    Patient generates a temporary 6-digit access code.
    Valid for 15 minutes by default with patient-configured scope.
    """
    _, patient = patient_data
    req_scope = payload.scope if payload and payload.scope else ["visit_summary", "recent_reports", "lab_data"]
    expiry = payload.expiry_minutes if payload and payload.expiry_minutes else 15
    max_uses = payload.max_uses if payload and payload.max_uses else 5

    token, plain_code = OTPService.create_access_token(
        db=db,
        patient_id=patient.id,
        scope=req_scope,
        expiry_minutes=expiry,
        max_uses=max_uses
    )

    now = datetime.datetime.utcnow()
    is_active = (not token.is_revoked) and (token.expires_at > now) and (token.used_count < token.max_uses)

    return AccessTokenResponse(
        id=token.id,
        patient_id=patient.id,
        code=plain_code,
        scope=token.scope,
        expires_at=token.expires_at,
        used_count=token.used_count,
        max_uses=token.max_uses,
        is_revoked=token.is_revoked,
        is_active=is_active,
        created_at=token.created_at
    )


@router.get("", response_model=list[AccessTokenResponse])
def get_patient_access_tokens(
    patient_data: tuple[User, Patient] = Depends(get_current_patient),
    db: Session = Depends(get_db)
):
    """List all access codes generated by this patient"""
    _, patient = patient_data
    now = datetime.datetime.utcnow()

    tokens = db.query(AccessToken).filter(
        AccessToken.patient_id == patient.id
    ).order_by(AccessToken.created_at.desc()).all()

    results = []
    for t in tokens:
        is_active = (not t.is_revoked) and (t.expires_at > now) and (t.used_count < t.max_uses)
        results.append(AccessTokenResponse(
            id=t.id,
            patient_id=t.patient_id,
            code=t.code_display or "******",
            scope=t.scope,
            expires_at=t.expires_at,
            used_count=t.used_count,
            max_uses=t.max_uses,
            is_revoked=t.is_revoked,
            is_active=is_active,
            created_at=t.created_at
        ))
    return results


@router.post("/{token_id}/revoke")
def revoke_access_token(
    token_id: int,
    patient_data: tuple[User, Patient] = Depends(get_current_patient),
    db: Session = Depends(get_db)
):
    """
    Patient immediately revokes a temporary access code.
    Healthcare providers immediately lose access.
    """
    _, patient = patient_data
    OTPService.revoke_token(db=db, token_id=token_id, patient_id=patient.id)
    return {"message": "Access code successfully revoked. External access terminated."}
